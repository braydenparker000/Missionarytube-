#!/usr/bin/env node
// Writes docs/claude-player/settings-status.md: the status of every reference
// preference key (frontend/claude-player/src/settings/pref-status.js), by screen.
// Usage: node scripts/claude-player/pref-status.mjs [--check]
//   --check exits 1 when the committed table is out of date.
import {readFileSync, writeFileSync} from 'node:fs';
import {gunzipSync} from 'node:zlib';
import {fileURLToPath} from 'node:url';
import {PREF_STATUS, prefKeys} from '../../frontend/claude-player/src/settings/pref-status.js';

const root = fileURLToPath(new URL('../../', import.meta.url));
const MODEL = root + 'frontend/claude-player/model/reference.json.gz';
export const DOC = root + 'docs/claude-player/settings-status.md';
const LABEL = {built: 'Built', ui: 'Settings UI', todo: 'Not built', web: 'No web counterpart', owner: 'Owner decision', na: 'Not applicable'};
const ORDER = ['built', 'ui', 'todo', 'web', 'owner', 'na'];

export function render(model) {
  const keys = prefKeys(model);
  const counts = Object.fromEntries(ORDER.map(s => [s, 0]));
  for (const {key} of keys) counts[PREF_STATUS[key]?.[0] ?? 'todo']++;
  const lines = [
    '# Claude Player settings status',
    '',
    'Generated by `node scripts/claude-player/pref-status.mjs` from',
    '`frontend/claude-player/src/settings/pref-status.js`; do not edit by hand.',
    `Every keyed entry of the reference preference XML (${keys.length} keys), by screen. Statuses:`,
    '',
    '- **Built:** the app reads the value and it changes behaviour.',
    '- **Settings UI:** a screen, category, link or text that the settings UI renders.',
    '- **Not built:** web-feasible but not built yet.',
    '- **No web counterpart:** the reason says why.',
    '- **Owner decision:** left out by an owner decision.',
    "- **Not applicable:** the reference's own business (purchases, support, updates).",
    '',
    'The settings screens show the last three greyed out, with a line saying why',
    '(`unavailableNote`), so no visible setting silently does nothing.',
    '',
    '| Status | Keys |',
    '| --- | ---: |',
    ...ORDER.map(s => `| ${LABEL[s]} | ${counts[s]} |`),
    '',
  ];
  keys.forEach(({key, screen, type}, i) => {
    if (keys[i - 1]?.screen !== screen) lines.push(`## ${screen}`, '', '| Key | Type | Status | Note |', '| --- | --- | --- | --- |');
    const [st, note] = PREF_STATUS[key] ?? ['todo', 'unclassified'];
    lines.push(`| \`${key}\` | ${type} | ${LABEL[st] ?? st} | ${(note || '').replace(/\|/g, '\\|')} |`);
    if (keys[i + 1]?.screen !== screen) lines.push('');
  });
  return lines.join('\n');
}

export function loadModel() {
  return JSON.parse(gunzipSync(readFileSync(MODEL)).toString());
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const text = render(loadModel());
  if (process.argv.includes('--check')) {
    let cur = '';
    try { cur = readFileSync(DOC, 'utf8'); } catch { /* missing */ }
    if (cur !== text) { console.error('settings-status.md is out of date: run node scripts/claude-player/pref-status.mjs'); process.exit(1); }
  } else writeFileSync(DOC, text);
}
