import {readFile,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {resolve} from 'node:path';
export function shuffleWorkerSource(player,handler){
  const start=player.indexOf('  class ShuffleCycle{'),end=player.indexOf('  const largeShuffle=',start);
  const shuffleStart=player.indexOf('function shuffleArray('),shuffleEnd=player.indexOf('\nfunction installSearchPlayback(',shuffleStart);
  if(start<0||end<start||shuffleStart<0||shuffleEnd<shuffleStart)throw Error('Shuffle source boundaries changed');
  return '// Generated by scripts/build-poweramp-shuffle-worker.mjs; do not edit.\n\'use strict\';\n'+player.slice(shuffleStart,shuffleEnd)+'\n'+player.slice(start,end)+'\n'+handler;
}
if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url)){
  const [player,handler]=await Promise.all([readFile(new URL('../public/drawercast/player.js',import.meta.url),'utf8'),readFile(new URL('./poweramp-shuffle-worker-handler.js',import.meta.url),'utf8')]);
  await writeFile(new URL('../public/drawercast/shuffle-worker.js',import.meta.url),shuffleWorkerSource(player,handler));
}
